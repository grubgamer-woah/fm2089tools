"""Writes tools/buttonfont.py: the serif capitals of the Wanzer setup buttons.

The game's buttons spell COM in a light serif, 10 px high. These glyphs are
Liberation Serif (SIL Open Font License) at the same cap height, kept at four
times the horizontal resolution so labels.py can narrow a word to fit a button.
Run once with Pillow and the font installed; the output needs neither.
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf'
CAP, SS, OVER = 10, 8, 4   # cap height, supersampling, stored horizontal resolution
CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-.&/'

size = 10
while True:
    f = ImageFont.truetype(FONT, size)
    b = f.getbbox('H')
    if b[3] - b[1] >= CAP*SS:
        break
    size += 1
top = f.getbbox('H')[1]
out = {}
for ch in CHARS:
    b = f.getbbox(ch)
    w = b[2] - b[0]
    g = Image.new('L', (w, CAP*SS), 0)
    ImageDraw.Draw(g).text((-b[0], -top), ch, font=f, fill=255)
    g = g.resize((max(1, round(w*OVER/SS)), CAP), Image.BOX)
    out[ch] = [''.join('%x' % round(g.getpixel((x, y))*15/255) for x in range(g.width)) for y in range(CAP)]

lines = ['"""Generated by dev/make_buttonfont.py from Liberation Serif (SIL Open Font License).',
         '',
         f'Each glyph: {CAP} rows of coverage 0-f, {OVER} columns per pixel."""', '',
         f'HEIGHT = {CAP}', f'OVER = {OVER}', 'GLYPHS = {']
for ch, rows in out.items():
    lines.append(f'    {ch!r}: (')
    lines += [f'        {r!r},' for r in rows]
    lines.append('    ),')
lines.append('}')
Path(__file__).resolve().parent.parent.joinpath('tools', 'buttonfont.py').write_text('\n'.join(lines)+'\n')
